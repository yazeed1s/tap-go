// Command gensdk generates the Tap API services and types in the root package
// from ref/api-spec.json. Run internal/cmd/buildspec first to refresh the spec.
//
// Every spec tag becomes one service on Client (Charges, Tokens, ...) in its
// own file. Schemas used by a single service are generated in that service's
// file; schemas used by several go to shared_types.go.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"net/http"
	"os"
	"sort"
	"strings"

	"github.com/yazeed1s/tap-go/internal/naming"
)

const (
	specPath  = "ref/api-spec.json"
	schemaRef = "#/components/schemas/"
	header    = "// Code generated by internal/cmd/gensdk from ref/api-spec.json; DO NOT EDIT.\n\n"
)

type spec struct {
	Tags       []tag                           `json:"tags"`
	Paths      map[string]map[string]operation `json:"paths"`
	Components struct {
		Schemas map[string]schema `json:"schemas"`
	} `json:"components"`
}

type tag struct {
	Name        string `json:"name"`
	Description string `json:"description"`
}

type operation struct {
	variant
	Tags       []string           `json:"tags"`
	Parameters []parameter        `json:"parameters"`
	Responses  map[string]apiResp `json:"responses"`
	Variants   []variant          `json:"x-tap-variants"`
}

type variant struct {
	OperationID  string               `json:"operationId"`
	GoName       string               `json:"x-go-name"`
	Summary      string               `json:"summary"`
	Description  string               `json:"description"`
	Deprecated   bool                 `json:"deprecated"`
	ExternalDocs struct{ URL string } `json:"externalDocs"`
	RequestBody  *requestBody         `json:"requestBody"`
}

type parameter struct {
	Name        string `json:"name"`
	In          string `json:"in"`
	Description string `json:"description"`
}

type requestBody struct {
	Content map[string]mediaType `json:"content"`
}

type apiResp struct {
	Content map[string]mediaType `json:"content"`
}

type mediaType struct {
	Schema schema `json:"schema"`
}

type schema struct {
	Ref                  string            `json:"$ref"`
	Type                 any               `json:"type"`
	Description          string            `json:"description"`
	Deprecated           bool              `json:"deprecated"`
	Enum                 []any             `json:"enum"`
	Required             []string          `json:"required"`
	Properties           map[string]schema `json:"properties"`
	Items                *schema           `json:"items"`
	AdditionalProperties json.RawMessage   `json:"additionalProperties"`
	OneOf                []schema          `json:"oneOf"`
	MixedTypes           []string          `json:"x-tap-mixed-types"`
	AnyOf                []schema          `json:"anyOf"`
}

// method is one generated service method.
type method struct {
	Name        string
	Summary     string
	Description string
	DocsURL     string
	Deprecated  bool
	HTTPMethod  string
	Path        string
	PathParams  []string
	Request     string // request schema name, "" when there is no body
	Response    string // response schema name, "" for text responses
	Text        bool   // response is text/plain (CSV downloads)
}

var methodOrder = []string{"get", "post", "put", "patch", "delete"}

func main() {
	data, err := os.ReadFile(specPath)
	if err != nil {
		log.Fatal(err)
	}
	var api spec
	if err := json.Unmarshal(data, &api); err != nil {
		log.Fatal(err)
	}

	g := &generator{api: api, methods: map[string][]method{}}
	g.collect()
	g.assignOwners()

	must(g.writeServices())
	must(g.writeSharedTypes())
	for _, t := range api.Tags {
		if len(g.methods[t.Name]) > 0 {
			must(g.writeService(t))
		}
	}
	must(g.writeExampleTest())
}

// writeExampleTest emits a map from schema name to a constructor for its Go
// type, used by spec_examples_test.go to decode every documented response
// example and docs sample, so a wrong type in the spec fails go test.
func (g *generator) writeExampleTest() error {
	names := make([]string, 0, len(g.owners))
	for name := range g.owners {
		names = append(names, name)
	}
	sort.Strings(names)
	var buf bytes.Buffer
	buf.WriteString(header + "package tap\n\n")
	buf.WriteString("var schemaTypes = map[string]func() any{\n")
	for _, name := range names {
		fmt.Fprintf(&buf, "\t%q: func() any { return new(%s) },\n", name, naming.Export(name))
	}
	buf.WriteString("}\n")
	return writeGoFile("schema_types_gen_test.go", buf.Bytes())
}

type generator struct {
	api     spec
	methods map[string][]method
	owners  map[string]string // schema name -> tag name or "shared"
}

func (g *generator) collect() {
	for _, path := range sortedKeys(g.api.Paths) {
		for _, httpMethod := range methodOrder {
			op, ok := g.api.Paths[path][httpMethod]
			if !ok {
				continue
			}
			if len(op.Tags) == 0 {
				log.Fatalf("%s %s has no tag", httpMethod, path)
			}
			variants := op.Variants
			if len(variants) == 0 {
				variants = []variant{op.variant}
			}
			for _, v := range variants {
				m, ok := g.method(path, httpMethod, op, v)
				if !ok {
					continue
				}
				g.methods[op.Tags[0]] = append(g.methods[op.Tags[0]], m)
			}
		}
	}
	for t, ms := range g.methods {
		sort.SliceStable(ms, func(i, j int) bool { return ms[i].Name < ms[j].Name })
		seen := map[string]bool{}
		for _, m := range ms {
			if seen[m.Name] {
				log.Fatalf("%s: duplicate method %s", t, m.Name)
			}
			seen[m.Name] = true
		}
	}
}

func (g *generator) method(path, httpMethod string, op operation, v variant) (method, bool) {
	m := method{
		Name:        v.GoName,
		Summary:     v.Summary,
		Description: v.Description,
		DocsURL:     v.ExternalDocs.URL,
		Deprecated:  v.Deprecated,
		HTTPMethod:  httpMethod,
		Path:        path,
	}
	if m.Name == "" {
		m.Name = naming.Export(v.OperationID)
	}
	for _, p := range op.Parameters {
		if p.In == "path" {
			m.PathParams = append(m.PathParams, p.Name)
		}
	}
	if v.RequestBody != nil {
		if media, ok := v.RequestBody.Content["application/json"]; ok {
			m.Request = refName(media.Schema.Ref)
		} else {
			// Multipart uploads are written by hand (see file_upload.go).
			fmt.Fprintf(os.Stderr, "gensdk: skipping %s (non-JSON request body)\n", v.OperationID)
			return m, false
		}
	}
	for _, code := range sortedKeys(op.Responses) {
		if !strings.HasPrefix(code, "2") {
			continue
		}
		content := op.Responses[code].Content
		if media, ok := content["application/json"]; ok {
			m.Response = refName(media.Schema.Ref)
		} else if _, ok := content["text/plain"]; ok {
			m.Text = true
		}
		break
	}
	return m, true
}

// assignOwners places each reachable schema in the file of the only service
// that uses it, or in shared_types.go when several do.
func (g *generator) assignOwners() {
	users := map[string]map[string]bool{}
	for t, ms := range g.methods {
		reach := map[string]bool{}
		for _, m := range ms {
			for _, name := range []string{m.Request, m.Response} {
				if name != "" {
					g.collectRefs(schema{Ref: schemaRef + name}, reach)
				}
			}
		}
		for name := range reach {
			if users[name] == nil {
				users[name] = map[string]bool{}
			}
			users[name][t] = true
		}
	}
	g.owners = map[string]string{}
	for name, ts := range users {
		g.owners[name] = "shared"
		if len(ts) == 1 {
			for t := range ts {
				g.owners[name] = t
			}
		}
	}
}

func (g *generator) collectRefs(s schema, reach map[string]bool) {
	if s.Ref != "" {
		name := refName(s.Ref)
		if reach[name] {
			return
		}
		reach[name] = true
		g.collectRefs(g.api.Components.Schemas[name], reach)
		return
	}
	for _, p := range s.Properties {
		g.collectRefs(p, reach)
	}
	if s.Items != nil {
		g.collectRefs(*s.Items, reach)
	}
	if extra := additional(s); extra != nil {
		g.collectRefs(*extra, reach)
	}
	for _, v := range append(append([]schema{}, s.OneOf...), s.AnyOf...) {
		g.collectRefs(v, reach)
	}
}

func (g *generator) writeServices() error {
	var buf bytes.Buffer
	buf.WriteString(header + "package tap\n\n")
	buf.WriteString("// Services holds one service per Tap API resource. It is embedded in\n")
	buf.WriteString("// Client, so services are used as client.Charges, client.Tokens, and so on.\n")
	buf.WriteString("type Services struct {\n")
	for _, t := range g.api.Tags {
		if len(g.methods[t.Name]) == 0 {
			continue
		}
		writeComment(&buf, "\t", t.Description)
		fmt.Fprintf(&buf, "\t%s *%sService\n", t.Name, t.Name)
	}
	buf.WriteString("}\n\n")
	buf.WriteString("func (s *Services) init(c *Client) {\n")
	for _, t := range g.api.Tags {
		if len(g.methods[t.Name]) > 0 {
			fmt.Fprintf(&buf, "\ts.%s = &%sService{client: c}\n", t.Name, t.Name)
		}
	}
	buf.WriteString("}\n")
	return writeGoFile("services.go", buf.Bytes())
}

func (g *generator) writeSharedTypes() error {
	var buf bytes.Buffer
	buf.WriteString(header + "package tap\n\n")
	for _, name := range g.ownedBy("shared") {
		g.writeSchema(&buf, name)
	}
	return writeGoFile("shared_types.go", buf.Bytes())
}

func (g *generator) writeService(t tag) error {
	ms := g.methods[t.Name]
	var buf bytes.Buffer
	buf.WriteString(header + "package tap\n\n")

	imports := []string{"context", "net/http"}
	for _, m := range ms {
		if _, ok := g.pager(m); ok {
			imports = append(imports, "iter")
			break
		}
	}
	for _, m := range ms {
		if len(m.PathParams) > 0 {
			imports = append(imports, "net/url")
			break
		}
	}
	sort.Strings(imports)
	buf.WriteString("import (\n")
	for _, imp := range imports {
		fmt.Fprintf(&buf, "\t%q\n", imp)
	}
	buf.WriteString(")\n\n")

	service := t.Name + "Service"
	writeComment(&buf, "", fmt.Sprintf("%s calls the Tap %s API. %s", service, t.Name, t.Description))
	fmt.Fprintf(&buf, "type %s struct {\n\tclient *Client\n}\n\n", service)
	for _, m := range ms {
		g.writeMethod(&buf, service, m)
		if p, ok := g.pager(m); ok {
			writeIterator(&buf, service, m, p)
		}
	}
	for _, name := range g.ownedBy(t.Name) {
		g.writeSchema(&buf, name)
	}
	return writeGoFile(fileName(t.Name), buf.Bytes())
}

func (g *generator) writeMethod(buf *bytes.Buffer, service string, m method) {
	doc := fmt.Sprintf("%s calls %s %s.", m.Name, strings.ToUpper(m.HTTPMethod), m.Path)
	if summary := strings.TrimSuffix(strings.TrimSpace(m.Summary), "."); summary != "" {
		doc = fmt.Sprintf("%s calls the %q endpoint.", m.Name, summary)
	}
	if desc := cleanDoc(m.Description); desc != "" && desc != m.Summary {
		doc += "\n\n" + desc
	}
	if m.DocsURL != "" {
		doc += "\n\nTap docs: " + m.DocsURL
	}
	if m.Deprecated {
		doc += "\n\nDeprecated: Tap marks this operation as deprecated."
	}
	writeComment(buf, "", doc)

	args := []string{"ctx context.Context"}
	for _, p := range m.PathParams {
		args = append(args, naming.Lower(naming.Export(p))+" string")
	}
	body := "nil"
	if m.Request != "" {
		args = append(args, "req "+m.Request)
		body = "req"
	}

	call := fmt.Sprintf("http.Method%s, %s, %s", httpConst(m.HTTPMethod), pathExpr(m.Path), body)
	switch {
	case m.Text:
		fmt.Fprintf(buf, "func (s *%s) %s(%s) ([]byte, error) {\n", service, m.Name, strings.Join(args, ", "))
		fmt.Fprintf(buf, "\treturn s.client.doRaw(ctx, %s)\n}\n\n", call)
	case m.Response == "":
		fmt.Fprintf(buf, "func (s *%s) %s(%s) error {\n", service, m.Name, strings.Join(args, ", "))
		fmt.Fprintf(buf, "\treturn s.client.do(ctx, %s, nil)\n}\n\n", call)
	default:
		fmt.Fprintf(buf, "func (s *%s) %s(%s) (*%s, error) {\n", service, m.Name, strings.Join(args, ", "), m.Response)
		fmt.Fprintf(buf, "\tvar out %s\n", m.Response)
		fmt.Fprintf(buf, "\tif err := s.client.do(ctx, %s, &out); err != nil {\n\t\treturn nil, err\n\t}\n", call)
		buf.WriteString("\treturn &out, nil\n}\n\n")
	}
}

// pager describes how to page through a list method.
type pager struct {
	Item       string // Go type of one list item
	ItemsField string // response field holding the items
	HasMore    string // Go expression, on page, that is true when no pages remain
	Cursor     string // request field set to the last item ID (cursor paging)
	Page       string // request field incremented (page-number paging)
}

// pager reports whether m is a list method the generator can iterate. Tap
// lists come in two styles: cursor (starting_after, set to the last item's
// id) and page number (page). Both report has_more. The response must have
// exactly one array of typed items.
func (g *generator) pager(m method) (pager, bool) {
	var p pager
	if !strings.HasPrefix(m.Name, "List") || m.Request == "" || m.Response == "" {
		return p, false
	}
	req := g.api.Components.Schemas[m.Request]
	resp := g.api.Components.Schemas[m.Response]

	hasMore, ok := resp.Properties["has_more"]
	if !ok || typeOf(hasMore) != "boolean" {
		return p, false
	}
	if g.fieldType(hasMore, contains(resp.Required, "has_more")) == "*bool" {
		p.HasMore = "page.HasMore == nil || !*page.HasMore"
	} else {
		p.HasMore = "!page.HasMore"
	}

	var arrays []string
	for _, name := range sortedKeys(resp.Properties) {
		prop := resp.Properties[name]
		if typeOf(prop) == "array" && prop.Items != nil && prop.Items.Ref != "" {
			arrays = append(arrays, name)
		}
	}
	if len(arrays) != 1 {
		return p, false
	}
	p.ItemsField = naming.Export(arrays[0])
	itemSchema := refName(resp.Properties[arrays[0]].Items.Ref)
	p.Item = naming.Export(itemSchema)
	item := g.api.Components.Schemas[itemSchema]

	switch {
	case typeOf(req.Properties["starting_after"]) == "string" &&
		typeOf(item.Properties["id"]) == "string" && len(item.Properties["id"].MixedTypes) == 0:
		p.Cursor = naming.Export("starting_after")
	case typeOf(req.Properties["page"]) == "integer":
		p.Page = naming.Export("page")
	default:
		return p, false
	}
	return p, true
}

// writeIterator emits <Method>All, which walks every page of a list method.
func writeIterator(buf *bytes.Buffer, service string, m method, p pager) {
	name := m.Name + "All"
	writeComment(buf, "", fmt.Sprintf(
		"%s iterates over every item %s returns, fetching further pages while\n"+
			"Tap reports has_more. It stops at the first error, which it yields\n"+
			"with a zero item. Stop early by breaking out of the range loop.", name, m.Name))
	fmt.Fprintf(buf, "func (s *%s) %s(ctx context.Context, req %s) iter.Seq2[%s, error] {\n",
		service, name, m.Request, p.Item)
	fmt.Fprintf(buf, "\treturn func(yield func(%s, error) bool) {\n", p.Item)
	if p.Page != "" {
		fmt.Fprintf(buf, "\t\tif req.%s == 0 {\n\t\t\treq.%s = 1\n\t\t}\n", p.Page, p.Page)
	}
	buf.WriteString("\t\tfor {\n")
	fmt.Fprintf(buf, "\t\t\tpage, err := s.%s(ctx, req)\n", m.Name)
	fmt.Fprintf(buf, "\t\t\tif err != nil {\n\t\t\t\tyield(%s{}, err)\n\t\t\t\treturn\n\t\t\t}\n", p.Item)
	fmt.Fprintf(buf, "\t\t\tfor _, item := range page.%s {\n\t\t\t\tif !yield(item, nil) {\n\t\t\t\t\treturn\n\t\t\t\t}\n\t\t\t}\n", p.ItemsField)
	fmt.Fprintf(buf, "\t\t\tif %s || len(page.%s) == 0 {\n\t\t\t\treturn\n\t\t\t}\n", p.HasMore, p.ItemsField)
	if p.Cursor != "" {
		fmt.Fprintf(buf, "\t\t\treq.%s = page.%s[len(page.%s)-1].ID\n", p.Cursor, p.ItemsField, p.ItemsField)
	} else {
		fmt.Fprintf(buf, "\t\t\treq.%s++\n", p.Page)
	}
	buf.WriteString("\t\t}\n\t}\n}\n\n")
}

func contains(list []string, v string) bool {
	for _, s := range list {
		if s == v {
			return true
		}
	}
	return false
}

// pathExpr turns "/v2/card/{customer_id}/{card_id}" into a Go string
// expression with escaped path arguments.
func pathExpr(path string) string {
	var parts []string
	lit := ""
	for path != "" {
		start := strings.IndexByte(path, '{')
		if start < 0 {
			lit += path
			break
		}
		end := strings.IndexByte(path[start:], '}') + start
		lit += path[:start]
		if lit != "" {
			parts = append(parts, fmt.Sprintf("%q", lit))
			lit = ""
		}
		arg := naming.Lower(naming.Export(path[start+1 : end]))
		parts = append(parts, "url.PathEscape("+arg+")")
		path = path[end+1:]
	}
	if lit != "" {
		parts = append(parts, fmt.Sprintf("%q", lit))
	}
	return strings.Join(parts, "+")
}

func (g *generator) writeSchema(buf *bytes.Buffer, name string) {
	s := g.api.Components.Schemas[name]
	goName := naming.Export(name)
	doc := cleanDoc(s.Description)
	if doc == "" {
		doc = goName + " is generated from the Tap API reference."
	}
	writeComment(buf, "", doc)

	switch {
	case len(s.Enum) > 0 && typeOf(s) == "string":
		fmt.Fprintf(buf, "type %s string\n\nconst (\n", goName)
		seen := map[string]bool{}
		for _, raw := range s.Enum {
			value := fmt.Sprint(raw)
			constName := goName + naming.Export(value)
			if !seen[constName] {
				seen[constName] = true
				fmt.Fprintf(buf, "\t%s %s = %q\n", constName, goName, value)
			}
		}
		buf.WriteString(")\n\n")
	case len(s.Properties) > 0:
		fmt.Fprintf(buf, "type %s struct {\n", goName)
		required := map[string]bool{}
		for _, r := range s.Required {
			required[r] = true
		}
		used := map[string]int{}
		for _, prop := range sortedKeys(s.Properties) {
			p := s.Properties[prop]
			field := naming.Export(prop)
			used[field]++
			if used[field] > 1 {
				field = fmt.Sprintf("%s%d", field, used[field])
			}
			writeComment(buf, "\t", cleanDoc(p.Description))
			if p.Deprecated {
				buf.WriteString("\t//\n\t// Deprecated: Tap marks this field as deprecated.\n")
			}
			tag := prop
			if !required[prop] {
				tag += ",omitempty"
			}
			fmt.Fprintf(buf, "\t%s %s `json:%q`\n", field, g.fieldType(p, required[prop]), tag)
		}
		buf.WriteString("}\n\n")
	default:
		fmt.Fprintf(buf, "type %s %s\n\n", goName, g.typeName(s))
	}
}

// fieldType is the Go type of a struct field. Optional nested structs are
// pointers so omitempty drops them, and optional booleans are *bool so an
// explicit false is still sent (Tap defaults some flags, like threeDSecure,
// to true).
func (g *generator) fieldType(s schema, required bool) string {
	if !required {
		if s.Ref != "" && len(g.api.Components.Schemas[refName(s.Ref)].Properties) > 0 {
			return "*" + g.typeName(s)
		}
		if typeOf(s) == "boolean" {
			return "*bool"
		}
	}
	return g.typeName(s)
}

func (g *generator) typeName(s schema) string {
	if len(s.MixedTypes) > 0 {
		return mixedType(s.MixedTypes)
	}
	if s.Ref != "" {
		return naming.Export(refName(s.Ref))
	}
	if variants := nonNull(append(append([]schema{}, s.OneOf...), s.AnyOf...)); len(variants) == 1 {
		return g.typeName(variants[0])
	} else if len(variants) > 1 {
		return "any"
	}
	switch typeOf(s) {
	case "string":
		return "string"
	case "integer":
		return "int64"
	case "number":
		return "float64"
	case "boolean":
		return "bool"
	case "array":
		if s.Items == nil {
			return "[]any"
		}
		return "[]" + g.typeName(*s.Items)
	case "object":
		if extra := additional(s); extra != nil {
			return "map[string]" + g.typeName(*extra)
		}
		return "map[string]any"
	}
	return "any"
}

func (g *generator) ownedBy(owner string) []string {
	var names []string
	for name, o := range g.owners {
		if o == owner {
			names = append(names, name)
		}
	}
	sort.Strings(names)
	return names
}

// mixedType picks the Go type for a field Tap sends with different JSON
// types. Numbers sent as numeric strings become FlexNumber (flexnumber.go);
// anything else (an object in one response, a string in another) is any.
func mixedType(types []string) string {
	numeric, str := false, false
	for _, t := range types {
		switch t {
		case "integer", "number":
			numeric = true
		case "string":
			str = true
		default:
			return "any"
		}
	}
	if numeric && str {
		return "FlexNumber"
	}
	return "any"
}

// additional returns the additionalProperties schema, or nil when it is
// absent or a boolean.
func additional(s schema) *schema {
	if len(s.AdditionalProperties) == 0 || s.AdditionalProperties[0] != '{' {
		return nil
	}
	var extra schema
	if json.Unmarshal(s.AdditionalProperties, &extra) != nil {
		return nil
	}
	if extra.Ref == "" && typeOf(extra) == "" {
		return nil
	}
	return &extra
}

func typeOf(s schema) string {
	switch t := s.Type.(type) {
	case string:
		return t
	case []any:
		for _, v := range t {
			if str, ok := v.(string); ok && str != "null" {
				return str
			}
		}
	}
	if len(s.Properties) > 0 {
		return "object"
	}
	return ""
}

func nonNull(list []schema) []schema {
	var out []schema
	for _, s := range list {
		if typeOf(s) != "null" {
			out = append(out, s)
		}
	}
	return out
}

func fileName(tagName string) string {
	return strings.Join(naming.Words(tagName), "_") + ".go"
}

func httpConst(method string) string {
	switch strings.ToUpper(method) {
	case http.MethodGet:
		return "Get"
	case http.MethodPost:
		return "Post"
	case http.MethodPut:
		return "Put"
	case http.MethodPatch:
		return "Patch"
	case http.MethodDelete:
		return "Delete"
	}
	log.Fatalf("unsupported HTTP method %s", method)
	return ""
}

func refName(ref string) string {
	return ref[strings.LastIndex(ref, "/")+1:]
}

func cleanDoc(doc string) string {
	doc = strings.ReplaceAll(doc, "\r\n", "\n")
	lines := strings.Split(strings.TrimSpace(doc), "\n")
	for i, line := range lines {
		lines[i] = strings.TrimRight(line, " \t")
	}
	return strings.Join(lines, "\n")
}

func writeComment(buf *bytes.Buffer, indent, text string) {
	if text == "" {
		return
	}
	for _, line := range strings.Split(text, "\n") {
		if line == "" {
			fmt.Fprintf(buf, "%s//\n", indent)
			continue
		}
		fmt.Fprintf(buf, "%s// %s\n", indent, line)
	}
}

func writeGoFile(path string, data []byte) error {
	formatted, err := format.Source(data)
	if err != nil {
		return fmt.Errorf("format %s: %w\n%s", path, err, data)
	}
	return os.WriteFile(path, formatted, 0o644)
}

func sortedKeys[T any](m map[string]T) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

