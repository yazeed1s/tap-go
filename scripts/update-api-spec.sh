#!/usr/bin/env bash
set -euo pipefail

SPEC_PATH="${SPEC_PATH:-ref/api-spec.json}"
CHECK_ONLY=0
FORCE=0
RUN_VERIFY=1
WATCH_INTERVAL=""

usage() {
	cat <<'USAGE'
Usage: scripts/update-api-spec.sh [--check] [--force] [--watch SECONDS] [--no-verify]

Rebuilds the Tap OpenAPI spec from the API reference at
https://developers.tap.company/reference, compares it with ref/api-spec.json,
and regenerates the SDK when it changes.

Tap does not publish a single OpenAPI file. internal/cmd/buildspec assembles
one from the definition embedded in every reference page.

Options:
  --check      Exit 0 when unchanged, exit 10 when the docs changed.
               Does not modify files.
  --force      Regenerate the SDK even when the spec is unchanged.
  --watch      Poll forever every SECONDS. Regenerates when the spec changes.
  --no-verify  Skip go test, go vet, and go build after regeneration.

Environment:
  SPEC_PATH    Local spec path. Defaults to ref/api-spec.json
USAGE
}

while (($#)); do
	case "$1" in
	--check)
		CHECK_ONLY=1
		;;
	--force)
		FORCE=1
		;;
	--watch)
		if (($# < 2)); then
			echo "--watch requires a seconds value" >&2
			exit 2
		fi
		WATCH_INTERVAL="$2"
		shift
		;;
	--no-verify)
		RUN_VERIFY=0
		;;
	-h | --help)
		usage
		exit 0
		;;
	*)
		echo "unknown argument: $1" >&2
		usage >&2
		exit 2
		;;
	esac
	shift
done

cd "$(dirname "$0")/.."

run_once() {
	local tmp
	tmp="$(mktemp)"
	trap 'rm -f "$tmp"' RETURN

	go run ./internal/cmd/buildspec -out "$tmp"

	if [[ -f "$SPEC_PATH" ]] && cmp -s "$tmp" "$SPEC_PATH" && ((!FORCE)); then
		echo "Tap OpenAPI spec is unchanged: $SPEC_PATH"
		return 0
	fi

	if ((CHECK_ONLY)); then
		echo "Tap OpenAPI spec changed"
		return 10
	fi

	mkdir -p "$(dirname "$SPEC_PATH")"
	cp "$tmp" "$SPEC_PATH"

	find . -maxdepth 1 -name '*.go' -print0 |
		xargs -0 grep -l '^// Code generated by internal/cmd/gensdk' 2>/dev/null |
		xargs -r rm -f || true

	go run ./internal/cmd/gensdk

	if command -v golines >/dev/null 2>&1; then
		find . -maxdepth 1 -name '*.go' -print0 |
			xargs -0 golines \
				-w \
				-m 80 \
				--no-ignore-generated
	else
		find . -maxdepth 1 -name '*.go' -print0 | xargs -0 gofmt -w
	fi

	if ((RUN_VERIFY)); then
		go test ./...
		go vet ./...
		go build ./...
	fi

	echo "Tap OpenAPI spec updated and SDK regenerated"
	return 0
}

if [[ -n "$WATCH_INTERVAL" ]]; then
	while true; do
		run_once || status=$?
		status="${status:-0}"
		if ((status != 0 && status != 10)); then
			exit "$status"
		fi
		unset status
		sleep "$WATCH_INTERVAL"
	done
fi

run_once
